import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

import { HUB_ID, readGameMetas } from './games'

// The hub (plugins/idle-arcade) lists every game and installs them all through
// `dependencies`. Both follow .claude-plugin/marketplace.json, so a merged game
// reaches the hub with one `bun run hub`.

export const titleOf = (id: string): string =>
  id
    .split('-')
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ')

export function gamesSource(root: string): string {
  const rows = readGameMetas(root).map(
    g => `  { id: ${JSON.stringify(g.id)}, title: ${JSON.stringify(titleOf(g.id))}, author: ${JSON.stringify(g.author)} },`,
  )

  return [
    '// Generated by scripts/hub.ts from .claude-plugin/marketplace.json: run `bun run hub`.',
    'export type Game = { id: string; title: string; author: string }',
    '',
    'export const GAMES: readonly Game[] = [',
    ...rows,
    ']',
    '',
  ].join('\n')
}

const bumpPatch = (v: string): string => {
  const [maj = '0', min = '0', pat = '0'] = v.split('.')

  return `${maj}.${min}.${Number(pat) + 1}`
}

export type HubSync = { changed: boolean; files: string[] }

// write: false only reports what would change.
export function syncHub(root: string, write: boolean): HubSync {
  const dir = join(root, 'plugins', HUB_ID)
  const manifestPath = join(dir, '.claude-plugin', 'plugin.json')
  const gamesPath = join(dir, 'hooks', 'games.ts')

  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const deps = readGameMetas(root).map(g => g.id)
  const games = gamesSource(root)
  const oldGames = existsSync(gamesPath) ? readFileSync(gamesPath, 'utf8') : ''
  const depsChanged = JSON.stringify(manifest.dependencies ?? []) !== JSON.stringify(deps)
  const gamesChanged = oldGames !== games
  const files: string[] = []
  if (depsChanged) files.push('plugins/' + HUB_ID + '/.claude-plugin/plugin.json')
  if (gamesChanged) files.push('plugins/' + HUB_ID + '/hooks/games.ts')

  if (write && files.length > 0) {
    if (depsChanged) {
      manifest.dependencies = deps
      // installed copies are cached by version: a new dependency list needs a new version
      manifest.version = bumpPatch(manifest.version ?? '0.1.0')
      writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n')
    }
    if (gamesChanged) writeFileSync(gamesPath, games)
  }

  return { changed: files.length > 0, files }
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, '..')
  const check = process.argv.includes('--check')
  const r = syncHub(root, !check)
  if (check && r.changed) {
    console.error('hub out of date with the marketplace (run `bun run hub`):\n  ' + r.files.join('\n  '))
    process.exit(1)
  }
  console.log(r.changed ? 'hub updated: ' + r.files.join(', ') : 'hub: in sync')
}
